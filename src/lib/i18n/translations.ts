/**
 * UI string translations for EN, DE, SL and PL.
 *
 * Rules:
 * - Compound names (BPC-157, Semaglutide, etc.) stay in English always.
 * - Units (mcg, mg, IU, ml) stay as-is.
 * - Proper nouns (GitHub, Discord, Vercel, IndexedDB) stay as-is.
 * - No em dashes anywhere. Use commas or restructure sentences.
 * - Keys are snake_case. Every language must have every key, which is
 *   enforced by a test rather than by the type: `satisfies Record<Lang,
 *   Record<string, string>>` accepts a language that is missing half of them,
 *   and a missing key falls back to English silently.
 *
 * On `{n}` and the Slavic plural. Slovenian and Polish both inflect a noun
 * several ways depending on the number in front of it, and `t()` has no plural
 * support, so "{n} vials" cannot be translated word for word: any single form
 * is wrong for most values of n. Those strings are phrased around the number
 * instead, "Enakih vialk: {n}", "Identycznych fiolek: {n}", which is correct
 * for every n and is also how labels read in the wild in both languages. The
 * same trick handles names, which would otherwise need a genitive the template
 * cannot produce.
 */

